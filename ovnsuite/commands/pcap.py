"""
ovnctl pcap -- port of ovn-pcap.sh

Captures traffic from VM logical ports using OVS port mirroring (SPAN).

For each target VM:
  1. a dedicated internal capture port is created on br-int
     (<mirror_prefix>-<vm>) -- its name never changes, unlike the VM's tap
  2. an OVS mirror copies the VM tap's ingress AND egress into it
  3. tcpdump writes rotated pcaps

The capture survives a VM restart: only the mirror's source port needs
re-pointing (--restart), while the tcpdump process and its output files
stay put.

DIRECT MODE: leave work_dir empty (or equal to directory) and tcpdump
writes straight into the destination -- no staging, no move. That is right
when the consumer takes files away itself. Its one requirement is that the
consumer triggers on CLOSE_WRITE, not on file creation.
"""

